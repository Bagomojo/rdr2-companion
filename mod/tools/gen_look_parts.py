"""Generates mod/LookParts.cs from the community RDR2 clothing hash list.

Source: https://github.com/femga/rdr3_discoveries (clothes/cloth_hash_names.lua), saved to
C:\\src\\rdr2-tools\\rdr3_discoveries. Face-feature and body-type hashes come from the open-source
VORP character creator (VORPCORE/vorp_character, config.lua).

Usage: python -I mod/tools/gen_look_parts.py <path to cloth_hash_names.lua>
"""

import re
import sys
from collections import OrderedDict
from pathlib import Path

ENTRY = re.compile(
    r'hashname="(?P<name>[^"]*)",category_hashname="(?P<cat>[^"]+)",ped_type="(?P<ped>[^"]+)",'
    r'is_multiplayer=(?P<mp>true|false),category_hash=0x[0-9A-Fa-f]+,hash=0x(?P<hash>[0-9A-Fa-f]+)'
)

# Clothing categories offered in the editor, with the name prefix that keeps period-plausible items.
CLOTHES = OrderedDict([
    ("Shirt", "shirts_full"),
    ("Vest", "vests"),
    ("Coat", "coats"),
    ("Pants", "pants"),
    ("Boots", "boots"),
    ("Hat", "hats"),
    ("Neckwear", "neckwear"),
])

HORSE = OrderedDict([
    ("Saddle", "horse_saddles"),
    ("Blanket", "horse_blankets"),
    ("Stirrups", "saddle_stirrups"),
])


def load(path):
    rows = []
    for m in ENTRY.finditer(Path(path).read_text(encoding="utf-8", errors="replace")):
        if m["name"] and m["name"] != m["cat"]:
            rows.append((m["name"], m["cat"], m["ped"], m["mp"] == "true", int(m["hash"], 16)))
    return rows


def cs_list(name, items):
    body = ",\n".join(f'            ("{n}", 0x{h:08X}u)' for n, h in items)
    return f"        public static readonly (string Name, uint Hash)[] {name} =\n        {{\n{body}\n        }};\n"


def main(src):
    rows = load(src)
    male = [r for r in rows if r[2] == "male" and r[3]]
    horse = [r for r in rows if r[2] == "horse"]

    def by_cat(cat, pool=male):
        seen, out = set(), []
        for name, c, *_ , h in pool:
            if c == cat and name not in seen:
                seen.add(name)
                out.append((name, h))
        return sorted(out)

    out = [
        "// Generated by mod/tools/gen_look_parts.py. Do not edit by hand.\n",
        "namespace KitCompanion\n{\n    internal static class LookParts\n    {\n",
    ]
    for label, cat in [("Heads", "heads"), ("BodiesUpper", "BODIES_UPPER"), ("BodiesLower", "BODIES_LOWER"),
                       ("Hair", "hair"), ("Beards", "beards_complete"), ("Eyes", "eyes")]:
        out.append(cs_list(label, by_cat(cat)))
    for label, cat in CLOTHES.items():
        out.append(cs_list(label, by_cat(cat)))
    for label, cat in HORSE.items():
        out.append(cs_list("Horse" + label, by_cat(cat, horse)))
    out.append("    }\n}\n")
    target = Path(__file__).resolve().parent.parent / "LookParts.cs"
    target.write_text("".join(out), encoding="utf-8")
    counts = {label: len(by_cat(cat)) for label, cat in [("heads", "heads"), ("hair", "hair"), ("beards", "beards_complete"), ("eyes", "eyes")]}
    print(f"wrote {target} {counts}")


if __name__ == "__main__":
    main(sys.argv[1])
